    bridge_server = FogBridgeServer(logger, "[TEST_SRV]", ipc_port, socket_timeout=5.0)
    bridge_client = FogBridgeClient(logger, "[TEST_CLI]", ipc_port, socket_timeout=5.0)

    # Generate complex simulated model weights (list of Numpy NDArrays)
    simulated_weights = [
        np.random.rand(128, 256).astype(np.float32), 
        np.array([1.0, 3.14, 42.0], dtype=np.float64)
    ]

    server_exceptions = []

    def bridge_server_task():
        # TEST 3.1 & 3.2: Run 3 consecutive rounds to prove the socket binds and drops cleanly without deadlocking
        for round_num in [1, 2, 3]:
            try:
                logger.debug(f"[IPC SERVER] Waiting for START command for round {round_num}...")
                received_round = bridge_server.wait_for_start()
                
                if received_round == round_num:
                    logger.debug(f"[IPC SERVER] START {received_round} validated. Injecting weights into stream...")
                    bridge_server.relay_weights(simulated_weights)
                else:
                    server_exceptions.append(f"Expected round {round_num}, got {received_round}")
            except Exception as e:
                server_exceptions.append(str(e))

    t_ipc = threading.Thread(target=bridge_server_task)
    t_ipc.start()
    time.sleep(0.2) # Allow server to bind

    # Client initiates the 3 consecutive rounds
    client_success_count = 0
    for round_num in [1, 2, 3]:
        received_weights, status, _ = bridge_client.execute_round(current_round=round_num)
        
        # Verify weight transfer math
        if status == 1 and len(received_weights) == 2:
            match_1 = np.array_equal(received_weights[0], simulated_weights[0])
            match_2 = np.array_equal(received_weights[1], simulated_weights[1])
            
            if match_1 and match_2:
                client_success_count += 1
                logger.debug(f"[IPC CLIENT] Round {round_num} complete. Mathematical equivalence verified.")
            else:
                logger.error(f"❌ IPC Bridge data corruption during round {round_num}.")
        
        time.sleep(0.1) # Small buffer between socket connections

    t_ipc.join(timeout=2.0)

    if client_success_count == 3 and not server_exceptions:
        logger.info("✅ IPC Custom Bridge: Successful consistency across multiple rounds. Tensors serialized natively.")
    else:
        logger.error(f"❌ IPC Custom Bridge Failed. Success count: {client_success_count}/3. Server Exceptions: {server_exceptions}")
        sys.exit(1)

    print("\n" + "#"*80)
    print("🎉 ALL COMMUNICATION & CRYPTOGRAPHY TESTS PASSED. 🎉")
    print("#"*80 + "\n")

