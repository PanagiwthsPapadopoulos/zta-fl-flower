    rogue_nginx_ctx.load_verify_locations(cafile=EDGE_CA)
    run_ssl_handshake_test(rogue_nginx_ctx, edge_client_ctx, "Edge<->Fog Rogue NGINX Server Rejected", expect_success=False)


    # =====================================================================
    # CATEGORY 3: CUSTOM IPC BRIDGE (fog_bridge.py / ipc.py)
    # =====================================================================
    print_separator("3. INTERNAL IPC BRIDGE (Fog <-> Fog Supernode)")
    logger.debug("Testing continuous state stability and complex weight transfer over plaintext localhost sockets.")

    ipc_port = find_free_port()
